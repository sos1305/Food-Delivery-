# 1. Authentication
# --------------------------------------------------------------------------
class AuthService:
    def __init__(self):
        self.users = {u["username"]: User(**u) for u in storage.load("users", [])}
        if "admin" not in self.users:
            self._create("admin", "admin123", role="admin")

    @staticmethod
    def _hash(password: str, salt_hex: str) -> str:
        salt = bytes.fromhex(salt_hex)
        if hasattr(hashlib, "pbkdf2_hmac"):
            return hashlib.pbkdf2_hmac("sha256", password.encode(), salt, 100_000).hex()
        # Some browser (Pyodide) builds ship without OpenSSL's PBKDF2; fall back
        # to salted, iterated SHA-256 so the app still works there.
        digest = salt + password.encode()
        for _ in range(20_000):
            digest = hashlib.sha256(digest).digest()
        return digest.hex()

    def _create(self, username, password, role="customer", phone="", address="") -> User:
        salt = os.urandom(16).hex()
        user = User(username, self._hash(password, salt), salt, role, phone, address)
        self.users[username] = user
        self._save()
        return user

    def _save(self):
        storage.save("users", [u.to_dict() for u in self.users.values()])

    def register(self, username, password, phone="", address="") -> User:
        username = username.strip().lower()
        if not re.fullmatch(r"[a-z0-9_]{3,20}", username):
            raise ValueError("Username must be 3-20 letters, digits or underscores.")
        if username in self.users:
            raise ValueError("That username is already taken.")
        if len(password) < 6:
            raise ValueError("Password must be at least 6 characters.")
        if phone and not re.fullmatch(r"\d{10}", phone):
            raise ValueError("Phone number must be 10 digits.")
        return self._create(username, password, "customer", phone, address)

    def login(self, username, password) -> User:
        user = self.users.get(username.strip().lower())
        if not user or self._hash(password, user.salt) != user.password_hash:
            raise ValueError("Invalid username or password.")
        return user

    def update_address(self, username, address):
        self.users[username].address = address
        self._save()



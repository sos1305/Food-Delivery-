# ------------------------------ file backend ------------------------------
def data_dir() -> str:
    return os.environ.get(
        "FOOD_APP_DATA",
        os.path.join(os.path.dirname(os.path.abspath(__file__)), "data"),
    )


def _path(name: str) -> str:
    return os.path.join(data_dir(), f"{name}.json")
"""test_app.py - unit tests for the Online Food Ordering System.

Run with:  python -m unittest test_app -v
"""
import os
import tempfile
import unittest

os.environ["FOOD_APP_DATA"] = tempfile.mkdtemp()

import services as s  # noqa: E402  (must come after the env var is set)
import storage  # noqa: E402


class FoodAppTests(unittest.TestCase):
    def setUp(self):
        for f in os.listdir(storage.data_dir()):
            os.remove(os.path.join(storage.data_dir(), f))
        self.auth = s.AuthService()
        self.menu = s.MenuService()
        self.orders = s.OrderService(self.menu)

    # --- auth ---
    def test_register_and_login(self):
        self.auth.register("Soumya", "secret1", "9876543210", "Delhi")
        self.assertEqual(self.auth.login("soumya", "secret1").address, "Delhi")
        with self.assertRaises(ValueError):
            self.auth.login("soumya", "wrong")

    def test_duplicate_and_weak_password(self):
        self.auth.register("amit", "secret1")
        with self.assertRaises(ValueError):
            self.auth.register("amit", "secret1")
        with self.assertRaises(ValueError):
            self.auth.register("neha", "123")

    def test_passwords_are_hashed(self):
        self.auth.register("amit", "secret1")
        self.assertNotIn("secret1", str(storage.load("users", [])))

    # --- menu ---
    def test_search_filters(self):
        veg = self.menu.search(veg_only=True)
        self.assertTrue(all(i.veg for i in veg))
        self.assertTrue(all("biryani" in i.name.lower() for i in self.menu.search("biryani")))
        self.assertTrue(all(i.price <= 100 for i in self.menu.search(max_price=100)))

    # --- cart & billing ---
    def test_cart_totals(self):
        cart = s.Cart(self.menu)
        cart.add(1, 2)  # Paneer Tikka 220
        cart.add(9, 4)  # Butter Naan 45
        self.assertEqual(cart.subtotal(), 620.0)
        cart.set_qty(9, 0)
        self.assertEqual(cart.subtotal(), 440.0)

    def test_coupons_and_bill(self):
        self.assertEqual(s.apply_coupon("WELCOME10", 500), 50.0)
        self.assertEqual(s.apply_coupon("WELCOME10", 5000), 100.0)  # capped
        with self.assertRaises(ValueError):
            s.apply_coupon("FLAT50", 100)  # below minimum
        bill = s.calculate_bill(400)  # below Rs.500 -> delivery fee applies
        self.assertEqual(bill["delivery_fee"], 30.0)
        self.assertEqual(bill["total"], 400 + 20 + 30)
        self.assertEqual(s.calculate_bill(600)["delivery_fee"], 0.0)

    def test_unavailable_item_cannot_be_added(self):
        self.menu.toggle_availability(1)
        with self.assertRaises(ValueError):
            s.Cart(self.menu).add(1)
class MenuService:
    def __init__(self):
        raw = storage.load("menu", None)
        if raw is None:
            raw = [
                MenuItem(i, n, c, float(p), v).to_dict()
                for i, (n, c, p, v) in enumerate(DEFAULT_MENU, start=1)
            ]
            storage.save("menu", raw)
        self.items = {d["id"]: MenuItem(**d) for d in raw}

    def _save(self):
        storage.save("menu", [i.to_dict() for i in self.items.values()])

    def categories(self):
        return sorted({i.category for i in self.items.values()})

    def get(self, item_id: int) -> MenuItem:
        if item_id not in self.items:
            raise ValueError(f"No menu item with id {item_id}.")
        return self.items[item_id]

    def search(self, query="", category="", veg_only=False, max_price=None,
               include_unavailable=False):
        q = query.strip().lower()
        out = []
        for item in self.items.values():
            if not include_unavailable and not item.available:
                continue
            if q and q not in item.name.lower():
                continue
            if category and item.category.lower() != category.strip().lower():
                continue
            if veg_only and not item.veg:
                continue
            if max_price is not None and item.price > max_price:
                continue
            out.append(item)
        return sorted(out, key=lambda i: (i.category, i.name))

    # --- admin operations ---
    def add_item(self, name, category, price, veg=True) -> MenuItem:
        if not name.strip() or not category.strip():
            raise ValueError("Name and category are required.")
        if price <= 0:
            raise ValueError("Price must be positive.")
        new_id = max(self.items, default=0) + 1
        item = MenuItem(new_id, name.strip(), category.strip().title(), float(price), veg)
        self.items[new_id] = item
        self._save()
        return item

    def update_price(self, item_id, price):
        if price <= 0:
            raise ValueError("Price must be positive.")
        self.get(item_id).price = float(price)
        self._save()

    def toggle_availability(self, item_id) -> bool:
        item = self.get(item_id)
        item.available = not item.available
        self._save()
        return item.available

    def remove_item(self, item_id):
        self.get(item_id)
        del self.items[item_id]
        self._save()